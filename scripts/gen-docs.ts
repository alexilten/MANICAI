/**
 * Generates docs/STANDARDS.md, docs/PRESETS.md and docs/PRECEDENTS.md from the data the app uses,
 * so the documentation cannot drift from the engine. Run: npm run docs
 */
import { writeFileSync } from 'node:fs';
import { CHECKED, PRECEDENTS, TOOLS } from '../src/core/data/precedents';
import { RULES } from '../src/core/data/standards';
import { ROOF_LABEL } from '../src/core/engine/architecture';
import { clearStadiumCache, resolveStadium } from '../src/core/engine/stadium';
import { PRESETS, precedentOf } from '../src/core/presets';

const esc = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
const head = (title: string, intro: string) => `# ${title}\n\n_Generated by \`npm run docs\` from the Manica source data. Do not edit by hand._\n\n${intro}\n\n`;

// ── standards
{
  let md = head('Standards and assumptions registry', [
    'Every rule Manica applies or reports, with its kind and how it was verified.',
    '',
    '- **governing**: a rule of the sport or a code requirement.',
    '- **guidance**: published design guidance (FIFA, SGSA Green Guide).',
    '- **assumption**: a Manica planning default. You can change it in the project.',
    '- **engineer-review**: outside what the tool can decide. A qualified professional must check it.',
    '',
    `Verification: **checked** means the rule was read in the cited source on the date shown. **recall** means it is reference knowledge that was not re-read this round, and it must be checked before you rely on it. Standards change and vary by jurisdiction. Manica is a planning tool, not a code-compliance tool.`,
  ].join('\n'));
  const topics = [...new Set(RULES.map((r) => r.topic))];
  for (const t of topics) {
    md += `## ${t}\n\n| id | statement | value | kind | verification | source |\n|---|---|---|---|---|---|\n`;
    for (const r of RULES.filter((x) => x.topic === t)) {
      const src = r.url ? `[${esc(r.source)}](${r.url})` : esc(r.source);
      md += `| \`${r.id}\` | ${esc(r.statement)} | ${esc(r.value ?? '')} | ${r.kind} | ${r.verification}${r.checked ? ` ${r.checked}` : ''} | ${src} |\n`;
    }
    md += '\n';
  }
  writeFileSync('docs/STANDARDS.md', md);
}

// ── presets
{
  let md = head('Presets', [
    'Presets are starting points. **Generic** presets use Manica planning defaults. **Precedent-informed studies** are independent parametric bowls built from a few published facts about a real project: capacity, sport, tier count and roof type. The engine fits the row counts to the published capacity.',
    '',
    'They are **not** the architects\' geometry, they use no drawings or CAD, and they are not affiliated with or endorsed by MANICA, Populous, HOK or any studio named. Confidence is **low** for all precedent presets because only the capacity and a qualitative bowl description are published.',
  ].join('\n'));
  md += '| preset | sport | target | capacity | suites | gross | tiers | rows | roof | worst C (mm) | farthest seat (m) | confidence |\n|---|---|---:|---:|---:|---:|---:|---:|---|---:|---:|---|\n';
  const detail: string[] = [];
  for (const pr of PRESETS) {
    clearStadiumCache();
    const p = pr.build();
    const s = resolveStadium(p);
    const m = s.metrics;
    md += `| ${pr.name} | ${pr.sport === 'nfl' ? 'NFL' : 'Soccer'} | ${p.bowl.targetCapacity.toLocaleString('en-US')} | ${m.total.toLocaleString('en-US')} | ${s.building.metrics.suites} | ${m.gross.toLocaleString('en-US')} | ${p.tiers.length} | ${p.tiers.map((t) => t.rows).join(' / ')} | ${ROOF_LABEL[p.architecture.roof.type]} | ${Math.round(m.c.min)} | ${(m.viewing.maxFarCorner / 1000).toFixed(0)} | ${pr.confidence} |\n`;
    const prec = precedentOf(pr);
    let d = `### ${pr.name}\n\n${pr.short}.\n\n`;
    if (prec) d += `Precedent: **${prec.name}** (${prec.location}). Status: ${prec.status.value}${prec.status.note ? ` (${prec.status.note})` : ''}. Credits: ${prec.credits.value}\n\n`;
    if (pr.verified.length) d += `**Published (sourced in [PRECEDENTS.md](PRECEDENTS.md)):**\n\n${pr.verified.map((v) => `- ${v}`).join('\n')}\n\n`;
    d += `**Assumed by Manica:**\n\n${pr.assumed.map((v) => `- ${v}`).join('\n')}\n\n`;
    const warns = s.warnings.filter((w) => w.level !== 'info');
    if (warns.length) d += `**Checks raised:**\n\n${warns.map((w) => `- ${w.message}`).join('\n')}\n\n`;
    detail.push(d);
  }
  md += `\n${detail.join('')}`;
  writeFileSync('docs/PRESETS.md', md);
}

// ── precedents
{
  let md = head('Precedent library', [
    `Research status as of ${CHECKED}. Each fact is tagged: **checked** means it was read in the cited source during research, **recall** means it is reference knowledge to verify before publication, and **inferred** means it is Manica's reading of public material.`,
    '',
    'Proposals and competition entries are labelled as such and are never presented as completed buildings.',
  ].join('\n'));
  const firms = ['MANICA', 'Populous', 'HOK', 'ROSSETTI', 'Other'] as const;
  for (const f of firms) {
    const list = PRECEDENTS.filter((p) => p.firm === f);
    if (!list.length) continue;
    md += `## ${f === 'Other' ? 'Other (listed in the brief)' : f}\n\n`;
    for (const p of list) {
      md += `### ${p.name}\n\n- **Location:** ${p.location} · **Type:** ${p.typology} · **Sport:** ${p.sport}\n`;
      md += `- **Status:** ${p.status.value} _(${p.status.v})_${p.status.note ? ` · ${p.status.note}` : ''}\n`;
      if (p.year) md += `- **Year:** ${p.year.value} _(${p.year.v})_\n`;
      md += `- **Credits:** ${p.credits.value} _(${p.credits.v})_\n`;
      if (p.capacity) md += `- **Capacity:** ${p.capacity.value.toLocaleString('en-US')} _(${p.capacity.v})_${p.capacity.note ? ` · ${p.capacity.note}` : ''}\n`;
      if (p.roof) md += `- **Roof:** ${p.roof.value} _(${p.roof.v})_\n`;
      if (p.bowl) md += `- **Bowl:** ${p.bowl.value} _(${p.bowl.v})_\n`;
      for (const x of p.features ?? []) md += `- ${x}\n`;
      if (p.sources.length) md += `- **Sources:** ${p.sources.map((s, i) => `[${i + 1}](${s})`).join(' · ')}\n`;
      md += '\n';
    }
  }
  md += '## Tools in the landscape\n\n';
  for (const t of TOOLS) md += `- **${t.name}:** ${t.note} ([source](${t.source}), checked ${t.checked})\n`;
  writeFileSync('docs/PRECEDENTS.md', md);
}
